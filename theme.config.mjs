/**
 * Active theme — the single config point for every build step (scripts, Vite, Lambda sync).
 *
 *   THEME=<folder> npm run build       # env var wins
 *   echo THEME=<folder> >> .env        # or a git-ignored .env at the repo root
 *   (nothing)                          # default: the committed sample theme
 *
 * A theme is a folder under templates/<name>/ that follows the contract described in README.md
 * (theme.mjs · tokens.json · template.src.html · v2-layouts.mjs · schema.json · prompt-style.md · assets/).
 *
 * Importing this module also refreshes templates/_active.mjs, a two-line git-ignored shim that re-exports the
 * active theme's theme.mjs. web/src/lib/themes.js imports that shim, so the same source file works under Vite,
 * plain Node (scripts) and — after sync-templates rewrites the import — inside the Lambda bundle.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const ROOT = dirname(fileURLToPath(import.meta.url));

function themeFromDotEnv() {
  try {
    return readFileSync(join(ROOT, ".env"), "utf8").match(/^\s*THEME\s*=\s*"?([\w.-]+)"?\s*$/m)?.[1];
  } catch {
    return undefined;
  }
}

export const THEME = process.env.THEME || themeFromDotEnv() || "sample";
export const THEME_DIR = join(ROOT, "templates", THEME);
export const ACTIVE_SHIM = join(ROOT, "templates", "_active.mjs");

if (!existsSync(join(THEME_DIR, "theme.mjs")))
  throw new Error(`Theme folder not found: templates/${THEME} (needs theme.mjs). Check the THEME env var or .env.`);

/** (Re)write the shim only when its content changes, so Vite's watcher does not loop. */
export function writeActiveShim() {
  const body = `// Generated by theme.config.mjs — git-ignored, do not edit. Active theme: ${THEME}\nexport { default } from "./${THEME}/theme.mjs";\n`;
  if (!existsSync(ACTIVE_SHIM) || readFileSync(ACTIVE_SHIM, "utf8") !== body) writeFileSync(ACTIVE_SHIM, body);
  return ACTIVE_SHIM;
}
writeActiveShim();

/** The active theme's descriptor (default export of templates/<THEME>/theme.mjs). */
export const loadTheme = async () => (await import(pathToFileURL(join(THEME_DIR, "theme.mjs")).href)).default;
